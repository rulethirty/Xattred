#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd -P)"
cd "$ROOT"
mkdir -p "$ROOT/.cache/clang" "$ROOT/.cache/swiftpm" "$ROOT/.tmp"
export CLANG_MODULE_CACHE_PATH="$ROOT/.cache/clang"
export SWIFTPM_MODULECACHE_OVERRIDE="$ROOT/.cache/clang"
export TMPDIR="$ROOT/.tmp/"
swift build -c release --product Xattred --build-system native --disable-sandbox --cache-path "$ROOT/.cache/swiftpm"
BIN="$(swift build -c release --build-system native --disable-sandbox --cache-path "$ROOT/.cache/swiftpm" --show-bin-path)"
APP="$ROOT/dist/Xattred.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/Xattred" "$APP/Contents/MacOS/Xattred"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
swift "$ROOT/scripts/make-icon.swift" "$ROOT/.build/Xattred.iconset"
/usr/bin/iconutil -c icns "$ROOT/.build/Xattred.iconset" -o "$APP/Contents/Resources/Xattred.icns"
/usr/bin/codesign --force --sign - "$APP"
/usr/bin/plutil -lint "$APP/Contents/Info.plist"
/usr/bin/codesign --verify --strict "$APP"
printf '\nBuilt: %s\n' "$APP"